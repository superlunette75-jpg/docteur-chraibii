// Writes the full page in each language so search engines and AI assistants read the real
// content without running JavaScript:
//   site/index.html (French), site/en/index.html, site/ar/index.html
//   + sitemap.xml, robots.txt, llms.txt
// Run after changing site/data.js or site/index.html:  npm run prerender
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";
import { parseHTML } from "linkedom";

const here = path.dirname(fileURLToPath(import.meta.url));
const SITE = path.join(here, "..", "site");

// Load the same data and renderer the browser uses
const ctx = { console };
ctx.window = ctx;
vm.createContext(ctx);
for (const f of ["data.js", "render.js"]) vm.runInContext(fs.readFileSync(path.join(SITE, f), "utf8"), ctx, { filename: f });
const { CLINIC: C, I18N, SERVICES, Render } = ctx;

const BASE = C.siteUrl.replace(/\/$/, "");
const LANGS = ["fr", "en", "ar"];
const OG_LOCALE = { fr: "fr_MA", en: "en_US", ar: "ar_MA" };
const url = lang => BASE + Render.PATHS[lang];
const attr = s => Render.esc(s);
const DAY_NAMES = ["Sunday", "Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday"];

function openingHours() {
  const groups = new Map();
  for (let d = 0; d < 7; d++) for (const [o, c] of C.hours[d] || []) {
    const k = o + "-" + c;
    if (!groups.has(k)) groups.set(k, []);
    groups.get(k).push(DAY_NAMES[d]);
  }
  return [...groups].map(([k, days]) => {
    const [opens, closes] = k.split("-");
    return { "@type": "OpeningHoursSpecification", dayOfWeek: days, opens, closes };
  });
}

function jsonLd(lang) {
  const t = I18N[lang];
  const id = BASE + "/#clinic";
  const clinic = {
    "@type": ["Dentist", "MedicalClinic"],
    "@id": id,
    name: C.name,
    alternateName: ["Dr. Chraibi", "Cabinet dentaire Dr. Chraibi Saada", "عيادة الدكتور الشرايبي لطب الأسنان"],
    description: t.seoDesc,
    url: BASE + "/",
    image: [BASE + "/images/og.jpg", BASE + "/images/cabinet.webp", BASE + "/images/attente.webp"],
    logo: BASE + "/icons/icon-512.png",
    telephone: "+" + C.whatsapp,
    address: {
      "@type": "PostalAddress",
      streetAddress: C.plusCode + ", Saada",
      addressLocality: "Marrakech",
      addressRegion: "Marrakech-Safi",
      addressCountry: "MA"
    },
    geo: { "@type": "GeoCoordinates", latitude: C.lat, longitude: C.lng },
    hasMap: C.mapsUrl,
    sameAs: [C.mapsUrl],
    areaServed: { "@type": "City", name: "Marrakech" },
    medicalSpecialty: "Dentistry",
    isAcceptingNewPatients: true,
    knowsLanguage: ["ar", "fr", "en"],
    openingHoursSpecification: openingHours(),
    aggregateRating: { "@type": "AggregateRating", ratingValue: String(C.rating), reviewCount: String(C.reviewsCount), bestRating: "5" },
    availableService: SERVICES.map(s => ({ "@type": "MedicalProcedure", name: s.name[lang], description: s.desc[lang] })),
    potentialAction: {
      "@type": "ReserveAction",
      target: { "@type": "EntryPoint", urlTemplate: "https://wa.me/" + C.whatsapp, actionPlatform: ["http://schema.org/MobileWebPlatform", "http://schema.org/DesktopWebPlatform"] },
      result: { "@type": "Reservation", name: t.bookLong }
    }
  };
  const page = {
    "@type": "WebPage",
    "@id": url(lang) + "#page",
    url: url(lang),
    name: t.seoTitle,
    description: t.seoDesc,
    inLanguage: lang,
    isPartOf: { "@type": "WebSite", "@id": BASE + "/#site", url: BASE + "/", name: C.name, inLanguage: LANGS },
    about: { "@id": id },
    primaryImageOfPage: BASE + "/images/hero-d.webp"
  };
  const faq = {
    "@type": "FAQPage",
    "@id": url(lang) + "#faq",
    inLanguage: lang,
    mainEntity: Render.faqList(t).map(([q, a]) => ({ "@type": "Question", name: q, acceptedAnswer: { "@type": "Answer", text: a } }))
  };
  return JSON.stringify({ "@context": "https://schema.org", "@graph": [clinic, page, faq] }, null, 1).replace(/</g, "\\u003c");
}

function seoBlock(lang) {
  const t = I18N[lang];
  const alt = LANGS.map(l => `  <link rel="alternate" hreflang="${l}" href="${url(l)}">`).join("\n");
  return `<!-- seo:start (generated by scripts/prerender.mjs) -->
  <title>${attr(t.seoTitle)}</title>
  <meta name="description" content="${attr(t.seoDesc)}">
  <meta name="robots" content="index, follow, max-image-preview:large, max-snippet:-1">
  <link rel="canonical" href="${url(lang)}">
${alt}
  <link rel="alternate" hreflang="x-default" href="${url("fr")}">
  <meta property="og:type" content="website">
  <meta property="og:site_name" content="${attr(C.name)}">
  <meta property="og:title" content="${attr(t.ogTitle)}">
  <meta property="og:description" content="${attr(t.seoDesc)}">
  <meta property="og:url" content="${url(lang)}">
  <meta property="og:image" content="${BASE}/images/og.jpg">
  <meta property="og:image:width" content="1200">
  <meta property="og:image:height" content="630">
  <meta property="og:locale" content="${OG_LOCALE[lang]}">
${LANGS.filter(l => l !== lang).map(l => `  <meta property="og:locale:alternate" content="${OG_LOCALE[l]}">`).join("\n")}
  <meta name="twitter:card" content="summary_large_image">
  <meta name="geo.region" content="MA-07">
  <meta name="geo.placename" content="Marrakech">
  <meta name="geo.position" content="${C.lat};${C.lng}">
  <meta name="ICBM" content="${C.lat}, ${C.lng}">
  <script type="application/ld+json">
${jsonLd(lang)}
  </script>
  <!-- seo:end -->`;
}

const source = fs.readFileSync(path.join(SITE, "index.html"), "utf8");
for (const lang of LANGS) {
  const { document } = parseHTML(source);
  Render.apply(document, lang, { todayIdx: -1 });
  let html = "<!doctype html>\n" + document.documentElement.outerHTML + "\n";
  html = html.replace(/<!-- seo:start[\s\S]*?<!-- seo:end -->/, seoBlock(lang));
  const out = path.join(SITE, Render.PATHS[lang], "index.html");
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, html);
  console.log("wrote", path.relative(SITE, out));
}

// sitemap with language alternates
const today = new Date().toISOString().slice(0, 10);
const links = LANGS.map(l => `    <xhtml:link rel="alternate" hreflang="${l}" href="${url(l)}"/>`).join("\n") +
  `\n    <xhtml:link rel="alternate" hreflang="x-default" href="${url("fr")}"/>`;
fs.writeFileSync(path.join(SITE, "sitemap.xml"), `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml" xmlns:image="http://www.google.com/schemas/sitemap-image/1.1">
${LANGS.map(l => `  <url>
    <loc>${url(l)}</loc>
    <lastmod>${today}</lastmod>
${links}
    <image:image><image:loc>${BASE}/images/hero-d.webp</image:loc></image:image>
    <image:image><image:loc>${BASE}/images/cabinet.webp</image:loc></image:image>
  </url>`).join("\n")}
</urlset>
`);

